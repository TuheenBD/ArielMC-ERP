// Helper functions for dynamic roadmap lookup
export function getRoadmapItemByCode(code: string): ProductRoadmapItem | undefined {
  return MASTER_PRODUCT_ROADMAP.find((item) => item.code === code);
}

export function getRoadmapItemsBySector(sector: ProductSector): ProductRoadmapItem[] {
  return MASTER_PRODUCT_ROADMAP.filter((item) => item.sector === sector);
}

export function getCategoriesBySector(sector: ProductSector): string[] {
  const items = getRoadmapItemsBySector(sector);
  return Array.from(new Set(items.map((i) => i.category)));
}

export function getSubCategoriesByCategory(sector: ProductSector, category: string): string[] {
  const items = MASTER_PRODUCT_ROADMAP.filter((i) => i.sector === sector && i.category === category);
  return Array.from(new Set(items.map((i) => i.subCategory)));
}
